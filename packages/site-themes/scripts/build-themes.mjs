// Turns the built-in themes' files (themes/<id>/…) into themes/generated.ts, so the workers and
// the dashboard can import them without reading files at run time.
//
//   node packages/site-themes/scripts/build-themes.mjs          writes themes/generated.ts
//   node packages/site-themes/scripts/build-themes.mjs --check  fails when it is out of date
import { readFileSync, readdirSync, statSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { fileURLToPath } from 'node:url';

const THEMES = fileURLToPath(new URL('../themes/', import.meta.url));
const OUT = join(THEMES, 'generated.ts');
const IDS = ['gate', 'letter', 'magazine', 'newspaper', 'launch', 'night', 'zine', 'brief'];

/** A theme's files, by their path inside the theme, in a stable order. */
export function readTheme(id) {
  const root = join(THEMES, id);
  const files = {};
  const walk = (dir) => {
    for (const name of readdirSync(join(root, dir)).sort()) {
      const path = dir ? `${dir}/${name}` : name;
      if (statSync(join(root, path)).isDirectory()) walk(path);
      else if (/\.(html|css|json)$/.test(name))
        files[path] = readFileSync(join(root, path), 'utf8');
    }
  };
  walk('');
  return files;
}

export function generatedSource() {
  const themes = Object.fromEntries(IDS.map((id) => [id, readTheme(id)]));
  return `// Generated by scripts/build-themes.mjs from the files in themes/<id>/. Do not edit: change the
// files and run \`pnpm --filter @swarm/site-themes build:themes\`.
// prettier-ignore
export const THEME_FILES: Record<string, Record<string, string>> = ${JSON.stringify(themes, null, 1)};
`;
}

if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) {
  const source = generatedSource();
  if (process.argv.includes('--check')) {
    const current = (() => {
      try {
        return readFileSync(OUT, 'utf8');
      } catch {
        return '';
      }
    })();
    if (current !== source) {
      console.error(
        'themes/generated.ts is out of date. Run pnpm --filter @swarm/site-themes build:themes.',
      );
      process.exit(1);
    }
  } else {
    writeFileSync(OUT, source);
    console.log(`Wrote ${OUT}`);
  }
}
