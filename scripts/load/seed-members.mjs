#!/usr/bin/env node
// Phase 2 exit gate: writes SQL that seeds a staging Channel with SES mailbox simulator Members.
// See docs/load-testing.md.
//
//   node scripts/load/seed-members.mjs --channel ch_… [--count 100000] [--bounce 0.01]
//     [--complaint 0.005] [--run <tag>] [--complete-ramp [--ramp-domain sd_…]]
//     [--out scripts/load/out/seed.sql]
//
// Then apply it (from workers/api, so the staging D1 binding resolves):
//   node_modules/.bin/wrangler d1 execute DB --env staging --remote --file <out>
//
// Why SQL rather than the import API: an import of 100k Members runs through the analysis and
// chunked import jobs (minutes, and its reports count simulator addresses as role or test
// addresses), and an import of 1,000+ new Members puts the Channel's Reputation Ramp back to
// warming, which is exactly what the gate run must not be capped by. The gate measures the send
// pipeline (snapshot, fan-out, SES, feedback), so the Members go straight into `members` with
// the columns the import would set. Every row is plain INSERT … ON CONFLICT DO NOTHING, so a
// re-run with the same --run tag adds nothing.
//
// Addresses: <kind>+<run>-<n>@simulator.amazonses.com, with kind success, bounce (a hard
// bounce) or complaint, spread evenly through the list so every send batch carries some.
import { randomBytes } from 'node:crypto';
import { mkdirSync, writeFileSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { parseArgs } from 'node:util';

const { values } = parseArgs({
  options: {
    channel: { type: 'string' },
    count: { type: 'string', default: '100000' },
    bounce: { type: 'string', default: '0.01' },
    complaint: { type: 'string', default: '0.005' },
    run: { type: 'string' },
    'complete-ramp': { type: 'boolean', default: false },
    'ramp-domain': { type: 'string' },
    out: { type: 'string', default: 'scripts/load/out/seed.sql' },
    help: { type: 'boolean', short: 'h' },
  },
  strict: true,
});

if (values.help) {
  console.log(
    'Usage: seed-members.mjs --channel ch_… [--count N] [--bounce 0.01] [--complaint 0.005] [--run tag] [--complete-ramp [--ramp-domain sd_…]] [--out file]',
  );
  process.exit(0);
}

const fail = (message) => {
  console.error(`seed-members: ${message}`);
  process.exit(2);
};

const channelId = values.channel ?? '';
if (!/^ch_[0-9a-f]{32}$/.test(channelId)) fail('--channel must be a Channel id (ch_ + 32 hex).');
const count = Number(values.count);
if (!Number.isInteger(count) || count < 1 || count > 1_000_000) fail('--count is 1 to 1,000,000.');
const bounceShare = Number(values.bounce);
const complaintShare = Number(values.complaint);
for (const [name, share] of [
  ['bounce', bounceShare],
  ['complaint', complaintShare],
]) {
  if (!(share >= 0 && share < 0.5)) fail(`--${name} is a share between 0 and 0.5.`);
}
const run = values.run ?? new Date().toISOString().slice(0, 16).replace(/[-:T]/g, '');
if (!/^[a-z0-9]{1,24}$/i.test(run)) fail('--run is 1 to 24 letters and digits.');
// --complete-ramp alone means the shared platform domain's ramp; --ramp-domain a custom domain's.
const completeRamp = values['complete-ramp'];
const rampDomain = values['ramp-domain'] ?? null;
if (rampDomain !== null && !/^sd_[0-9a-f]{32}$/.test(rampDomain)) {
  fail('--ramp-domain is a sending domain id (sd_ + 32 hex).');
}
if (rampDomain !== null && !completeRamp) fail('--ramp-domain goes with --complete-ramp.');

/** The same id format as @swarm/domain newId: <prefix>_<UUIDv7 as 32 hex>. */
function newId(prefix, now) {
  const bytes = randomBytes(16);
  let ms = BigInt(now);
  for (let i = 5; i >= 0; i--) {
    bytes[i] = Number(ms & 0xffn);
    ms >>= 8n;
  }
  bytes[6] = (bytes[6] & 0x0f) | 0x70;
  bytes[8] = (bytes[8] & 0x3f) | 0x80;
  return `${prefix}_${bytes.toString('hex')}`;
}

/**
 * Spreads bounce and complaint addresses evenly: member n is one when its share "ticks over".
 * When both tick on the same member, the complaint moves to the next one.
 */
let owedComplaints = 0;
function kindOf(n) {
  const ticks = (share) => Math.floor((n + 1) * share) > Math.floor(n * share);
  if (ticks(complaintShare)) owedComplaints++;
  if (ticks(bounceShare)) return 'bounce';
  if (owedComplaints > 0) {
    owedComplaints--;
    return 'complaint';
  }
  return 'success';
}

const width = String(count).length;
const now = Date.now();
const lines = [
  `-- Generated by scripts/load/seed-members.mjs at ${new Date(now).toISOString()}.`,
  `-- Channel ${channelId}, run "${run}", ${count} Members.`,
];
const tally = { success: 0, bounce: 0, complaint: 0 };
// 200 rows (about 40 KB) per statement keeps each one far below D1's statement size limit.
const ROWS = 200;
let rows = [];
const flush = () => {
  if (!rows.length) return;
  lines.push(
    `INSERT INTO members (id, channel_id, email, first_name, last_name, status, source_json, consent_at, confirmed_at, created_at, updated_at) VALUES\n${rows.join(',\n')}\nON CONFLICT (channel_id, email) DO NOTHING;`,
  );
  rows = [];
};
for (let n = 0; n < count; n++) {
  const kind = kindOf(n);
  tally[kind]++;
  const email = `${kind}+${run}-${String(n).padStart(width, '0')}@simulator.amazonses.com`;
  // Ids carry the same millisecond, so the snapshot's id order is effectively shuffled.
  rows.push(
    `('${newId('mb', now)}', '${channelId}', '${email}', 'Load', '${kind}', 'active', '{"utm_source":"load-test","utm_campaign":"${run}"}', ${now}, ${now}, ${now}, ${now})`,
  );
  if (rows.length === ROWS) flush();
}
flush();

if (completeRamp) {
  // Staging only: the gate measures the pipeline at 100k, which a fresh ramp would spread over
  // weeks (the shared domain's ramp tops out at 5,000 a day). The row is created exactly as
  // ensureRamp (packages/engine/src/ramp.ts) would, then marked complete so it no longer caps.
  const domain = rampDomain ? `'${rampDomain}'` : 'NULL';
  const defaults = rampDomain
    ? { start: 200, growth: 1.5, max: 1_000_000 }
    : { start: 100, growth: 1.3, max: 5_000 };
  const day = new Date(now).toISOString().slice(0, 10);
  lines.push(
    `INSERT INTO reputation_ramps (id, channel_id, sending_domain_id, status, day, cap_today, start_cap, growth, max_cap, bounce_threshold, complaint_threshold, created_at, updated_at)
VALUES ('${newId('rr', now)}', '${channelId}', ${domain}, 'warming', '${day}', ${defaults.start}, ${defaults.start}, ${defaults.growth}, ${defaults.max}, 0.02, 0.0008, ${now}, ${now})
ON CONFLICT DO NOTHING;`,
    `UPDATE reputation_ramps SET status = 'complete', paused_reason = NULL, updated_at = ${now}
  WHERE channel_id = '${channelId}' AND ifnull(sending_domain_id, '') = '${rampDomain ?? ''}';`,
  );
}

const out = resolve(values.out);
mkdirSync(dirname(out), { recursive: true });
writeFileSync(out, `${lines.join('\n')}\n`);
console.log(
  JSON.stringify(
    { out, channelId, run, members: count, ...tally, rampCompleted: completeRamp },
    null,
    2,
  ),
);
