/** `/api/v1/dispatches/:dispatchId` → its parameter values, by name. */
function paramsOf(template: string, path: string): Record<string, string> {
  const want = template.split('/');
  const got = path.split('/');
  const out: Record<string, string> = {};
  want.forEach((part, i) => {
    if (part.startsWith(':') && got[i] !== undefined)
      out[part.slice(1)] = decodeURIComponent(got[i]);
  });
  return out;
}

async function tenantOf(
  db: D1Database,
  anchor: string,
  id: string,
): Promise<{ channelId: string | null; workspaceId: string | null } | null> {
  if (anchor === 'workspaceId') return { channelId: null, workspaceId: id };
  if (anchor === 'channelId') return { channelId: id, workspaceId: null };
  const rule = ANCHORS[anchor]!;
  return first<{ channelId: string | null; workspaceId: string | null }>(
    db,
    `SELECT ${rule.channel === false ? 'NULL' : 'channel_id'} AS channelId,
            ${rule.workspace ? 'workspace_id' : 'NULL'} AS workspaceId
       FROM ${rule.table} WHERE id = ?1`,
    id,
  );
}

export const routePolicy: MiddlewareHandler<AppEnv> = async (c, next) => {
  const route = matchedRoutes(c).find((r) => r.method !== 'ALL');
  if (!route) return next();
  const key = `${c.req.method === 'HEAD' ? 'GET' : c.req.method} ${route.path.replace(/:(\w+)/g, '{$1}')}`;
  const policy = ROUTE_POLICY[key];
  // Undeclared routes (the WebSocket upgrade, anything outside the document) keep their own checks.
  if (!policy || policy === 'public') return next();
  const auth = c.get('auth');
  if (!auth) throw new ApiError('unauthorized', 'Sign in to continue.');
  // A session that still owes a second factor gets mfa_required from the route itself.
  if (policy === 'signed-in' || auth.secondFactor !== 'ok') return next();

  const params = paramsOf(route.path, c.req.path);
  const anchor = Object.keys(params)[0];
  if (!anchor || !ANCHORS[anchor]) return next();
  const db = env(c).DB;
  const tenant = await tenantOf(db, anchor, params[anchor]!);
  // A row that doesn't exist is the route's own 404.
  if (!tenant) return next();
  let role: SeatRole | null | undefined;
  let workspaceId = tenant.workspaceId;
  if (tenant.channelId) {
    const access = await channelAccess(db, auth.operatorId, tenant.channelId);
    role = access?.role;
    workspaceId = access?.workspaceId ?? null;
  } else if (tenant.workspaceId) {
    role = await workspaceRole(db, auth.operatorId, tenant.workspaceId);
  }
  if (!role || !workspaceId)
    throw new ApiError('not_found', `${ANCHORS[anchor]!.label} not found.`);
  // The same reach rules as requireWorkspace and requireChannel, so no route can skip them.
  if (auth.ssoWorkspaceId !== null || auth.ssoBlockedWorkspaceId === workspaceId) {
    const seat = tenant.channelId ? await workspaceRole(db, auth.operatorId, workspaceId) : role;
    await checkSessionReach(c, auth, workspaceId, seat ?? role);
  }
  if (!roleAtLeast(role, policy)) {
    throw new ApiError('forbidden', `This needs the ${policy} role or higher.`);
  }
  return next();
};

