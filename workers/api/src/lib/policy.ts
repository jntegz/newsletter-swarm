/**
 * The route policy: every /api/v1 operation declares who may call it, and one middleware applies
 * the declaration before the route validates its input. `public` needs nothing (the route has its
 * own proof: a signed webhook, an OAuth state, a QuickPass token); `signed-in` needs a session;
 * a role is the minimum effective role on the workspace or Channel the path names.
 *
 * The handlers keep their own checks (requireChannel, requireOwned, …), which can be stricter;
 * this is the floor, and what tests/v1-matrix.test.ts generates its negative cases from. The test
 * fails for an operation that is missing here, so a new route can't ship without a declaration.
 */
